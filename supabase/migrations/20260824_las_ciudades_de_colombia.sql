-- Las 1.273 ciudades de Colombia con su codigo DANE, que es lo que pide 99envios.
--
-- 24 de agosto de 2026. Fase 1 de la integracion con 99envios.
--
-- Cotizar y crear una guia piden el codigo del DANE -Bogota es 11001000- y el
-- panel guarda la ciudad como texto libre, escrita por la clienta en el
-- checkout: "Bogota", "bogota", "BOGOTA D.C.". Sin esta tabla no hay forma de
-- pasar de lo uno a lo otro.
--
-- La lista sale del documento que 99envios reparte con su API. Se guarda
-- entera, INCLUIDOS los siete codigos que aparecen dos veces con nombres
-- distintos -"PATIA" y "EL BORDO" son el mismo 19532000-, porque esos alias
-- son justo lo que hace que una busqueda por nombre acierte mas.
--
-- 80 nombres se repiten en departamentos distintos, asi que el departamento no
-- es decoracion: sin el, "Santa Rosa" son ocho municipios.
--
-- LA CLAVE VA GUARDADA, no calculada en un indice. unaccent() es STABLE y no
-- IMMUTABLE -lee un diccionario-, asi que un indice sobre una expresion que la
-- use es una promesa que Postgres no puede sostener. Se normaliza al cargar,
-- que ademas es cuando se sabe que el texto no va a cambiar.

create table if not exists public.ciudades_envio (
  codigo             text not null,
  nombre             text not null,
  departamento       text not null,
  clave              text not null,
  clave_departamento text not null,
  primary key (codigo, nombre)
);

comment on table public.ciudades_envio is
  'Municipios de Colombia con su codigo DANE, para cotizar y crear guias en 99envios. Incluye alias: un mismo codigo puede aparecer con dos nombres.';

create index if not exists ciudades_envio_por_clave_idx
  on public.ciudades_envio (clave);

alter table public.ciudades_envio enable row level security;

drop policy if exists "ciudades_envio_lectura_equipo" on public.ciudades_envio;
create policy "ciudades_envio_lectura_equipo"
  on public.ciudades_envio for select
  to authenticated
  using (public.es_del_equipo());

-- Texto comparable, para lo que teclea la clienta. Es la misma idea que norm()
-- en el panel: nadie escribe tildes en un formulario.
create or replace function public.clave_de_ciudad(p_texto text)
returns text
language sql
stable
set search_path = public, extensions, pg_temp
as $$
  SELECT nullif(btrim(regexp_replace(upper(unaccent(coalesce(p_texto, ''))), '[^A-Z0-9]+', ' ', 'g')), '');
$$;

